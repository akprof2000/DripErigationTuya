bool tlsTimeValid() { return time(nullptr) >= TIME_VALID_FROM; }

void tlsConfigure(WiFiClientSecure& client) {
  if (tlsTimeValid()) {
    client.setCACert(ROOT_CA);
    return;
  }
  static bool warned = false;
  if (!warned) {
    warned = true;
    LOG_W("tls: часы ещё не идут — TLS без проверки сертификата до первой синхронизации");
  }
  client.setInsecure();
}
